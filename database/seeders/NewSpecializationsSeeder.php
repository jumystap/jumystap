<?php

namespace Database\Seeders;

use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\DB;

/**
 * Пополнение справочника отраслей и специальностей.
 *
 * Отдельный сидер, а не правка SpecializationSeeder: тот рассчитан на пустую
 * базу и делает insert без проверок, а здесь справочник уже наполнен.
 * Идемпотентен — повторный запуск ничего не продублирует.
 *
 * «Отрасль» в исходных данных — это specialization_categories: именно они
 * первый уровень выбора в форме вакансии. Таблица industries к форме не
 * подключена и здесь не используется.
 */
class NewSpecializationsSeeder extends Seeder
{
    /** Отрасль (name_ru существующей категории) => специальности [ru, kz]. */
    private const SPECIALIZATIONS = [
        'Швейное дело' => [
            ['Специалист на окантовочный станок', 'Окантовкалау станогының маманы'],
        ],
        'Общепит' => [
            ['Раздатчик еды', 'Тамақ таратушы'],
        ],
        'Образование' => [
            ['Переводчик', 'Аудармашы'],
        ],
        'Рабочий и тех. персонал' => [
            ['Спасатель', 'Құтқарушы'],
            ['Механизатор на хозяйство', 'Шаруашылық механизаторы'],
            ['Термист', 'Термист'],
            ['Дезинфектор', 'Дезинфектор'],
        ],
        'Медицина, фармацевтика' => [
            ['Оптик (окулист)', 'Оптик (офтальмолог)'],
            ['Оптометрист', 'Оптометрист'],
        ],
        'Финансы и право' => [
            // В русской таблице стояло «Аудит», в казахской — «Аудитор».
            // Взяли профессию, а не вид деятельности: справочник про людей.
            ['Аудитор', 'Аудитор'],
        ],
        'Салон красоты, фитнес, спорт' => [
            ['Администратор в салон красоты', 'Сұлулық салонының әкімшісі'],
            ['Мастер аквагрима', 'Аквагрим шебері'],
        ],
        'Производство' => [
            ['Оператор печатного принтера', 'Баспа принтерінің операторы'],
        ],
        'Строительство и ремонт' => [
            ['Машинист башенного крана', 'Мұнаралы кран машинисі'],
        ],
        'Офисная работа' => [
            ['Директор', 'Директор'],
            ['Дизайнер мебели', 'Жиһаз дизайнері'],
        ],
        'Автосервис' => [
            ['Шиномонтажник', 'Шиномонтажшы'],
            ['Кузовщик', 'Кузовшы'],
            // В источнике «Маляра» — падежная опечатка.
            ['Маляр', 'Бояушы'],
        ],
        'Развлечения' => [
            ['Оператор аттракциона', 'Аттракцион операторы'],
            ['Фотограф', 'Фотограф'],
        ],
    ];

    /** Новая отрасль: [name_ru, name_kz] => специальности. */
    private const NEW_CATEGORY = ['Полиграфия и издательское дело', 'Полиграфия және баспа ісі'];

    private const NEW_CATEGORY_SPECIALIZATIONS = [
        ['Оператор печатного принтера', 'Баспа принтерінің операторы'],
        ['Полиграфический дизайнер', 'Полиграфиялық дизайнер'],
        ['Аэродизайнер', 'Аэродизайнер'],
    ];

    public function run(): void
    {
        [$newCategoryRu, $newCategoryKz] = self::NEW_CATEGORY;

        DB::table('specialization_categories')->updateOrInsert(
            ['name_ru' => $newCategoryRu],
            ['name_kz' => $newCategoryKz, 'updated_at' => now(), 'created_at' => now()]
        );

        $groups = self::SPECIALIZATIONS + [$newCategoryRu => self::NEW_CATEGORY_SPECIALIZATIONS];

        foreach ($groups as $categoryRu => $specializations) {
            $category = DB::table('specialization_categories')->where('name_ru', $categoryRu)->first();

            if (! $category) {
                $this->command?->warn("Отрасль «{$categoryRu}» не найдена — специальности пропущены");

                continue;
            }

            foreach ($specializations as [$nameRu, $nameKz]) {
                // Уникальность в паре с категорией: «Фотограф» и «Маляр» уже
                // есть в других отраслях, и это разные профессии.
                DB::table('specializations')->updateOrInsert(
                    ['category_id' => $category->id, 'name_ru' => $nameRu],
                    ['name_kz' => $nameKz, 'updated_at' => now(), 'created_at' => now()]
                );
            }
        }
    }
}
